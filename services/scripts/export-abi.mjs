// Copies the EdgeEscrow ABI out of the Foundry build into a typed TS module.
// Run `forge build` in contracts/ first.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = resolve(here, "../../contracts/out/EdgeEscrow.sol/EdgeEscrow.json");
const target = resolve(here, "../src/abi/EdgeEscrow.ts");

const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by services/scripts/export-abi.mjs from contracts/out. Do not edit.\n` +
    `export const edgeEscrowAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`wrote ${abi.length} ABI entries to ${target}`);
